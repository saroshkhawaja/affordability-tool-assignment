rows = []
for line in raw.strip().split("\n"):
    parts = line.split(",")
    rows.append({
        "country_name": parts[0],
        "gni_per_capita_ppp": float(parts[1]),
        "price_level_ratio": round(float(parts[2]), 6),
        "inflation_pct": None if parts[3] == "" else round(float(parts[3]), 4),
        "education_spend_pct_gdp": None if parts[4] == "" else round(float(parts[4]), 4),
    })

