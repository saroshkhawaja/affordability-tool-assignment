# Reproduce the exact cleaning + clustering steps from clean_data.py
df = df_raw.dropna(subset=["gni_per_capita_ppp", "price_level_ratio", "inflation_pct"]).reset_index(drop=True)
print(f"Rows after dropping incomplete essential indicators: {len(df)}")

df["inflation_capped"] = df["inflation_pct"].clip(upper=40)
df["economic_instability_flag"] = df["inflation_pct"] > 40

